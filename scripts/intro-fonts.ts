#!/usr/bin/env node
// Fetches tiny Noto Sans subsets (OFL-1.1) holding only the glyphs of the welcome-animation syllables
// (apps/web/src/features/intro/syllables.ts), so phones download a few KB instead of whole fonts.
// Writes apps/web/public/fonts/intro/*.woff2 and apps/web/src/features/intro/intro-fonts.css.
// Usage: pnpm intro:fonts   (outputs are committed; rerun after changing the syllables)
// Google's subsetter keeps the glyphs that conjuncts and vowel signs need, so the browser shapes the
// syllables exactly as with the full font (checked by the screenshot comparison in docs/TESTING.md).
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { REEL_SCRIPTS, introFamily } from '../apps/web/src/features/intro/syllables.ts';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const outDir = join(root, 'apps/web/public/fonts/intro');
const cssOut = join(root, 'apps/web/src/features/intro/intro-fonts.css');
// A current Chrome user agent, so the API answers with woff2.
const UA =
  'Mozilla/5.0 (X11; Linux x86_64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/141.0.0.0 Safari/537.36';
const WEIGHT = 700;

const byFamily = new Map<string, string>();
for (const r of REEL_SCRIPTS) byFamily.set(r.family, (byFamily.get(r.family) ?? '') + r.syllables.join(''));

mkdirSync(outDir, { recursive: true });
const rules: string[] = [];
for (const [family, text] of byFamily) {
  const api = `https://fonts.googleapis.com/css2?family=${encodeURIComponent(family)}:wght@${WEIGHT}&text=${encodeURIComponent(text)}`;
  const css = await (await fetch(api, { headers: { 'user-agent': UA } })).text();
  const url = /src: url\((https:[^)]+)\) format\('woff2'\)/.exec(css)?.[1];
  const range = /unicode-range: ([^;]+);/.exec(css)?.[1];
  if (!url || !range) throw new Error(`${family}: unexpected API response:\n${css}`);
  const file = `${family.toLowerCase().replaceAll(' ', '-')}.woff2`;
  const bytes = new Uint8Array(await (await fetch(url)).arrayBuffer());
  writeFileSync(join(outDir, file), bytes);
  rules.push(
    `@font-face {\n  font-family: '${introFamily(family)}';\n  font-weight: ${WEIGHT};\n  font-display: block;\n  src: url('/fonts/intro/${file}') format('woff2');\n  unicode-range: ${range};\n}`,
  );
  console.log(`intro-fonts: ${file} ${bytes.length} bytes`);
}
writeFileSync(
  cssOut,
  `/* GENERATED by scripts/intro-fonts.ts — do not edit by hand. Noto Sans subsets, SIL OFL 1.1 (public/fonts/intro/OFL.txt). */\n${rules.join('\n')}\n`,
);
// The Noto fonts share one licence; ship it next to the files as the OFL requires.
const ofl = readFileSync(
  join(root, 'apps/web/node_modules/@fontsource-variable/noto-sans-malayalam/LICENSE'),
  'utf8',
);
writeFileSync(
  join(outDir, 'OFL.txt'),
  ofl.replace(/^Copyright .*$/m, 'Copyright 2022 The Noto Project Authors (https://github.com/notofonts)'),
);
