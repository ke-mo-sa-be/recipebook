#!/usr/bin/env node
// Generates database rows from the sources in supabase/seed/:
//   supabase/migrations/<latest>_reference_data*.sql       units, categories, regions, tags, dictionary
//                                                          (production reference data)
//   supabase/seed.sql                                      demo users and 12 sample recipes (dev/staging only)
// Usage: pnpm seed:build   (CI runs pnpm seed:check, which fails if the outputs are stale)
// Runs on Node 24's built-in TypeScript type stripping, so it can import packages/core directly.
import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { UNITS, type UnitCode } from '../packages/core/src/measures.ts';
import { detectTimerSeconds } from '../packages/core/src/timers.ts';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const src = (f: string) => join(root, 'supabase/seed', f);
// Reference data is a full, idempotent upsert. Applied migrations are never edited, so when the
// sources change, point this at a NEW timestamped file; earlier ones stay frozen as applied.
//   20261017090100_reference_data.sql     v0.2.0 (frozen)
//   20261019090100_reference_data_v2.sql  M3: "meen / മീൻ / fish" aliases on fish types
const REFERENCE_OUT = join(root, 'supabase/migrations/20261019090100_reference_data_v2.sql');
const SEED_OUT = join(root, 'supabase/seed.sql');
const HEADER = '-- GENERATED by scripts/build-seed.ts from supabase/seed/ — do not edit by hand.\n';

// ── SQL helpers ──────────────────────────────────────────────────────────────
const q = (v: string | null | undefined) => (v == null ? 'null' : `'${v.replaceAll("'", "''")}'`);
const n = (v: number | null | undefined) => (v == null ? 'null' : String(v));
const arr = (v: string[]) => `array[${v.map(q).join(', ')}]::text[]`;
/** Stable UUID from a name, so seeded recipe URLs never change between resets. */
function uuidFrom(name: string): string {
  const h = createHash('sha256').update(`paachakam:${name}`).digest('hex');
  return `${h.slice(0, 8)}-${h.slice(8, 12)}-4${h.slice(13, 16)}-8${h.slice(17, 20)}-${h.slice(20, 32)}`;
}

// ── sources ──────────────────────────────────────────────────────────────────
type Lookups = {
  categories: Array<{ id: number; slug: string; sticker: string }>;
  regions: Array<{ id: number; slug: string; grp: string }>;
  tags: Array<{ id: number; slug: string; kind: string }>;
  groupStickers: Record<string, string>;
};
const lookups: Lookups = JSON.parse(readFileSync(src('lookups.json'), 'utf8'));

type Ingredient = {
  slug: string;
  en: string;
  ml: string;
  aliases: string[];
  grp: string;
  sticker: string | null;
};
const ingredients: Ingredient[] = readFileSync(src('ingredients.psv'), 'utf8')
  .split('\n')
  .filter((l) => l.trim() && !l.startsWith('#'))
  .map((line) => {
    const [slug, en, ml, aliases, grp, sticker] = line.split('|').map((c) => c.trim());
    if (!slug || !en || !ml || !grp) throw new Error(`bad dictionary line: ${line}`);
    return {
      slug,
      en,
      ml,
      aliases: aliases
        ? aliases
            .split(';')
            .map((a) => a.trim())
            .filter(Boolean)
        : [],
      grp,
      sticker: sticker || null,
    };
  });
const ingredientSlugs = new Set(ingredients.map((i) => i.slug));
if (ingredientSlugs.size !== ingredients.length) throw new Error('duplicate dictionary slug');

// ── reference migration ──────────────────────────────────────────────────────
const ref: string[] = [
  HEADER,
  '-- Reference data for every environment. Upserts, so a later regenerate can extend it.\n',
];
ref.push('insert into public.units (code, kind, scalable, ml, g, traditional, whole) values');
ref.push(
  (Object.entries(UNITS) as Array<[UnitCode, (typeof UNITS)[UnitCode]]>)
    .map(([code, u]) => {
      const x = u as {
        kind: string;
        scalable: boolean;
        ml?: number;
        g?: number;
        traditional?: boolean;
        whole?: boolean;
      };
      return `  (${q(code)}, ${q(x.kind)}, ${x.scalable}, ${n(x.ml)}, ${n(x.g)}, ${Boolean(x.traditional)}, ${Boolean(x.whole)})`;
    })
    .join(',\n') +
    '\non conflict (code) do update set kind = excluded.kind, scalable = excluded.scalable, ml = excluded.ml, g = excluded.g,\n  traditional = excluded.traditional, whole = excluded.whole;\n',
);
ref.push('insert into public.categories (id, slug, sort, sticker) values');
ref.push(
  lookups.categories.map((c, i) => `  (${c.id}, ${q(c.slug)}, ${i + 1}, ${q(c.sticker)})`).join(',\n') +
    '\non conflict (id) do update set slug = excluded.slug, sort = excluded.sort, sticker = excluded.sticker;\n',
);
ref.push('insert into public.regions (id, slug, grp, sort) values');
ref.push(
  lookups.regions.map((r, i) => `  (${r.id}, ${q(r.slug)}, ${q(r.grp)}, ${i + 1})`).join(',\n') +
    '\non conflict (id) do update set slug = excluded.slug, grp = excluded.grp, sort = excluded.sort;\n',
);
ref.push('insert into public.tags (id, slug, kind) values');
ref.push(
  lookups.tags.map((t) => `  (${t.id}, ${q(t.slug)}, ${q(t.kind)})`).join(',\n') +
    '\non conflict (id) do update set slug = excluded.slug, kind = excluded.kind;\n',
);
ref.push('insert into public.ingredients (slug, name_en, name_ml, aliases, grp, sticker) values');
ref.push(
  ingredients
    .map(
      (i) =>
        `  (${q(i.slug)}, ${q(i.en)}, ${q(i.ml)}, ${arr(i.aliases)}, ${q(i.grp)}, ${q(i.sticker ?? lookups.groupStickers[i.grp] ?? null)})`,
    )
    .join(',\n') +
    '\non conflict (slug) do update set name_en = excluded.name_en, name_ml = excluded.name_ml, aliases = excluded.aliases,\n  grp = excluded.grp, sticker = excluded.sticker;\n',
);
const referenceSql = ref.join('\n');

// ── dev seed: demo users and recipes ─────────────────────────────────────────
type Line = {
  a: number | null;
  m?: number;
  u: UnitCode | null;
  i?: string;
  t: string;
  n?: string;
  g?: string;
};
type SeedRecipe = {
  author: string;
  title_ml: string;
  title_en: string;
  content_lang: 'ml' | 'en';
  description: string;
  category: string;
  region: string;
  diet: string;
  prep: number;
  cook: number;
  servings: number;
  tags: string[];
  ingredients: Line[];
  steps: string[];
  tips?: string;
  featured?: boolean; // shown in Home's featured row (admins pick these in production)
};
type SeedFile = {
  authors: Array<{
    handle: string;
    name: string;
    email: string;
    district: string;
    lang: string;
    bio: string;
  }>;
  recipes: SeedRecipe[];
};
const seed: SeedFile = JSON.parse(readFileSync(src('recipes.json'), 'utf8'));
const catId = new Map(lookups.categories.map((c) => [c.slug, c.id]));
const regionId = new Map(lookups.regions.map((r) => [r.slug, r.id]));
const tagId = new Map(lookups.tags.map((t) => [t.slug, t.id]));

const out: string[] = [
  HEADER,
  '-- Development / staging seed only — never load in production.',
  "-- Demo users sign in with the password 'demo-password'.\n",
];
for (const a of seed.authors) {
  const id = uuidFrom(`user:${a.handle}`);
  const meta = JSON.stringify({ display_name: a.name, lang: a.lang });
  out.push(`insert into auth.users (instance_id, id, aud, role, email, encrypted_password, email_confirmed_at,
  raw_app_meta_data, raw_user_meta_data, created_at, updated_at, confirmation_token, recovery_token, email_change_token_new, email_change)
values ('00000000-0000-0000-0000-000000000000', ${q(id)}, 'authenticated', 'authenticated', ${q(a.email)},
  extensions.crypt('demo-password', extensions.gen_salt('bf')), now(), '{"provider":"email","providers":["email"]}',
  ${q(meta)}, now(), now(), '', '', '', '')
on conflict (id) do nothing;
insert into auth.identities (id, user_id, provider_id, identity_data, provider, last_sign_in_at, created_at, updated_at)
values (${q(id)}, ${q(id)}, ${q(id)}, ${q(JSON.stringify({ sub: id, email: a.email, email_verified: true }))}, 'email', now(), now(), now())
on conflict do nothing;
update public.profiles set handle = ${q(a.handle)}, district = ${q(a.district)}, bio = ${q(a.bio)}, onboarded_at = now()
where id = ${q(id)};
`);
}

for (const [idx, r] of seed.recipes.entries()) {
  const id = uuidFrom(`recipe:${r.title_en}`);
  const author = seed.authors.find((a) => a.handle === r.author);
  if (!author) throw new Error(`unknown author ${r.author}`);
  const cat = catId.get(r.category);
  const reg = regionId.get(r.region);
  if (!cat || !reg) throw new Error(`${r.title_en}: unknown category/region`);
  // Stagger publish dates so "latest" has an order.
  const published = `now() - interval '${(seed.recipes.length - idx) * 7} hours'`;
  out.push(`-- ${r.title_en}`);
  out.push(`insert into public.recipes (id, author_id, title_ml, title_en, description, content_lang, category_id, region_id, diet,
  prep_minutes, cook_minutes, servings, tips, status, published_at)
values (${q(id)}, ${q(uuidFrom(`user:${author.handle}`))}, ${q(r.title_ml)}, ${q(r.title_en)}, ${q(r.description)}, ${q(r.content_lang)},
  ${cat}, ${reg}, ${q(r.diet)}, ${r.prep}, ${r.cook}, ${r.servings}, ${q(r.tips ?? null)}, 'draft', ${published})
on conflict (id) do nothing;`);
  r.ingredients.forEach((l, i) => {
    if (l.i && !ingredientSlugs.has(l.i)) throw new Error(`${r.title_en}: unknown ingredient ${l.i}`);
    if (l.u && !(l.u in UNITS)) throw new Error(`${r.title_en}: unknown unit ${l.u}`);
    out.push(`insert into public.recipe_ingredients (id, recipe_id, position, group_label, amount, amount_max, unit_code, ingredient_id, item_text, note)
values (${q(uuidFrom(`ing:${r.title_en}:${i}`))}, ${q(id)}, ${i}, ${q(l.g ?? null)}, ${n(l.a)}, ${n(l.m)}, ${q(l.u)},
  ${l.i ? `(select id from public.ingredients where slug = ${q(l.i)})` : 'null'}, ${q(l.t)}, ${q(l.n ?? null)})
on conflict (id) do nothing;`);
  });
  r.steps.forEach((body, i) => {
    out.push(`insert into public.recipe_steps (id, recipe_id, position, body, timer_seconds)
values (${q(uuidFrom(`step:${r.title_en}:${i}`))}, ${q(id)}, ${i}, ${q(body)}, ${n(detectTimerSeconds(body))})
on conflict (id) do nothing;`);
  });
  for (const t of r.tags) {
    const tid = tagId.get(t);
    if (!tid) throw new Error(`${r.title_en}: unknown tag ${t}`);
    out.push(
      `insert into public.recipe_tags (recipe_id, tag_id) values (${q(id)}, ${tid}) on conflict do nothing;`,
    );
  }
  // Publish last, so the publish check sees the ingredients and steps.
  out.push(`update public.recipes set status = 'published' where id = ${q(id)};\n`);
  if (r.featured) out.push(`update public.recipes set featured_at = ${published} where id = ${q(id)};\n`);
}
const seedSql = out.join('\n');

// ── write or check ───────────────────────────────────────────────────────────
const outputs: Array<[string, string]> = [
  [REFERENCE_OUT, referenceSql],
  [SEED_OUT, seedSql],
];
if (process.argv.includes('--check')) {
  const stale = outputs.filter(([file, sql]) => {
    try {
      return readFileSync(file, 'utf8') !== sql;
    } catch {
      return true;
    }
  });
  if (stale.length) {
    console.error(`seed: stale output, run pnpm seed:build:\n  ${stale.map(([f]) => f).join('\n  ')}`);
    process.exit(1);
  }
  console.log('seed: generated files are fresh');
} else {
  for (const [file, sql] of outputs) writeFileSync(file, sql);
  console.log(
    `seed: ${ingredients.length} ingredients, ${seed.recipes.length} recipes, ${seed.authors.length} demo users`,
  );
}
